package domain.policy

/** The first line of every file Loadout generates. */
const val GENERATED_OUTPUT_HEADER = "<!-- Generated by Loadout CLI -->"

/** How many leading bytes of a file [hasGeneratedOutputHeader] needs: the header and a line break. */
val GENERATED_OUTPUT_HEADER_PREFIX_BYTES = GENERATED_OUTPUT_HEADER.length + "\r\n".length

/** Whether [leadingContent], the start of a file, opens with Loadout's header line. */
fun hasGeneratedOutputHeader(leadingContent: String): Boolean =
    leadingContent.lineSequence().firstOrNull() == GENERATED_OUTPUT_HEADER
